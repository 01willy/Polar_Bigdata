def tex(s):
    return s.replace('%', '\\%').replace('&', '\\&').replace('#', '\\#').replace('_', '\\_')


def main():
    spec = json.load(open(SPEC, encoding='utf-8'))
    titles = {sl['id']: sl.get('title') for sl in spec['slides']}
    titles.setdefault('NG1', '워크플로 사용 절차')
    order = [sl['id'] for sl in spec['slides']]
    ids = [x[0] for x in SLIDES]
    missing = [i for i in order if i not in ids and i != 'S35']
    assert not missing, missing
    assert [i for i in ids if i in order] == [i for i in order if i in ids], 'order differs from spec'
    lines = ['% part1_script.tex : 발표 대본(재배열 최종 덱). gen_part1.py 가 만든다. 직접 고치지 말고 gen_part1.py 를 고친다.', '']
    total = 0.0
    pm = json.load(open(os.path.join(os.path.dirname(SPEC), 'render', 'paper_report_page_map.json'), encoding='utf-8'))
    for k, (sid, _num, mins, body, point, box) in enumerate(SLIDES):
        num = '표지' if k == 0 else str(k)
        assert sid not in pm or pm[sid] is None or str(pm[sid]) == num, (sid, pm.get(sid), num)
        total += mins
        lines.append('\\slideheading{%s}{%s}{%s}' % (num, tex(titles[sid]), ('%.1f' % mins)))
        lines.append('')
        lines.append(tex(body))
        lines.append('')
        lines.append('\\pointat{%s}' % tex(point))
        if box:
            lines.append('')
            lines.append('\\begin{optbox}')
            lines.append(tex(box))
            lines.append('\\end{optbox}')
        lines.append('')
    open(OUT, 'w', encoding='utf-8').write('\n'.join(lines))
    print('tex written, minutes %.1f, slides %d' % (total, len(SLIDES)))
    if '--spec' in sys.argv:
        n = 0
        for sl in spec['slides']:
            for sid, num, mins, body, point, box in SLIDES:
                if sl['id'] == sid:
                    sl.setdefault('notes', {})
                    sl['notes']['script'] = body
                    n += 1
        with open(SPEC, 'w', encoding='utf-8') as f:
            json.dump(spec, f, ensure_ascii=False, indent=1)

        print('spec notes.script updated:', n)


if __name__ == '__main__':
    main()

# -*- coding: utf-8 -*-
"""v11_numbers.py: 논문 초안 v11 의 추가 수치 매크로(그림 6 제품 지도 비교). 출력 paper/manuscript/shared_v11/numbers_v11.tex, docs/numbers_v11.json.
원천은 그림 6 의 source data(outputs/figures/paper/v11/source_data/Fig6_product_maps.json). 실행: python3 scripts/2_evaluation/v11_numbers.py
"""
from __future__ import annotations
import json, re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]; N = {}
RK = {"Alaska": "Ak", "Lena": "Le"}


def put(k, v):
    assert re.fullmatch(r"[A-Za-z]+", k), k; N[k] = v


f6 = json.load(open(ROOT / "outputs/figures/paper/v11/source_data/Fig6_product_maps.json"))
for reg, v in f6["values"].items():
    r = RK[reg]; ts = v["product_training_sites"]
    put(f"fe{r}N", str(v["n_common_cells"]))                 # 세 지도 공통 관측 셀 수
    put(f"fe{r}Year", str(v["year"]))
    put(f"fe{r}NearWei", str(ts["n_common_within_25km"]))     # Wei 학습 지점 25 km 안
    put(f"fe{r}FarWei", str(ts["n_common_gt25km"]))
    for k, src in (("Oof", "physics_residual_ml_block_cv"), ("Wei", "wei_2026"), ("Liu", "liu_2024")):
        put(f"fe{r}Bias{k}", f"{v['bias_common_cm'][src]:+.1f}".replace("-", "−"))
    # 그림 6 에 인쇄된 RMSE 와 v10 매크로(nfe*)가 같은지 확인
    printed = v["rmse_common_cm"]
    put(f"fe{r}RmseOofChk", f"{printed['physics_residual_ml_block_cv']:.1f}")

# 그림 7c: 레나 델타 관측 편차와 예측 편차의 일치(2020년 값 제외 시 강건성)
import numpy as np
f7 = json.load(open(ROOT / "outputs/figures/paper/v11/source_data/Fig7_maps.json"))["c"]["regions"]["Lena"]
ys = sorted(f7["observed_anomaly_cm"], key=int)
o = np.array([f7["observed_anomaly_cm"][y] for y in ys]); pr = np.array([f7["predicted_anomaly_cm"][y] for y in ys]); keep = np.array([y != "2020" for y in ys])
put("anobsrLeNoTwenty", f"{np.corrcoef(o[keep], pr[keep])[0, 1]:.2f}")
put("anobsLeTwentyObs", f"{f7['observed_anomaly_cm']['2020']:+.1f}".replace("-", "−"))
put("anobsLeTwentyN", str(f7["observed_n_cell_years"]["2020"]))

# 외부 CALM 채점 집합(스발바르 시추공 제외 뒤)과 비교별 행 수: 예측 파일과 extft_deltas.csv 에서 센다
import glob, pandas as pd
EX = ROOT / "data/processed/v5/runs/extra_v9"
PR = pd.concat([pd.read_csv(f) for f in sorted(glob.glob(str(EX / "preds_EXTFT_*.csv.gz")))], ignore_index=True)
q0 = PR[(PR.n_label.astype(str) == "0") & (PR.method == "R1S")].drop_duplicates("cell_year_id")
put("ftScoredRows", f"{len(q0):,}"); put("ftScoredCells", str(q0.loc_id.nunique())); put("ftScoredBlocks", str(q0.block.nunique()))
DL = pd.read_csv(EX / "extft_deltas.csv"); DL["n_label"] = DL.n_label.astype(str)
cc = DL[(DL.n_label == "5") & (DL.A == "R1S") & (DL.B == "ESA CCI v5")].iloc[0]
put("ftdCciRows", f"{int(cc.n):,}"); put("ftdCciBlocks", str(int(cc.n_blocks)))
rp = DL[(DL.n_label == "5") & (DL.A == "R1S") & (DL.B == "P1n")].iloc[0]
assert int(rp.n) == len(q0), (rp.n, len(q0))

out = ROOT / "paper/manuscript/shared_v11/numbers_v11.tex"; out.parent.mkdir(parents=True, exist_ok=True)
with open(out, "w") as fh:
    fh.write("% numbers_v11.tex: generated by scripts/2_evaluation/v11_numbers.py. Do not edit by hand.\n")
    for k, v in N.items():
        fh.write("\\providecommand{\\n" + k + "}{" + v + "}\n")
json.dump(N, open(ROOT / "docs/numbers_v11.json", "w"), ensure_ascii=False, indent=1)
v10 = json.load(open(ROOT / "docs/numbers_v10.json")) if (ROOT / "docs/numbers_v10.json").exists() else {}
for r in RK.values():
    a, b = N[f"fe{r}RmseOofChk"], v10.get(f"fe{r}Oofabs")
    print(f"{r}: figure RMSE {a} cm, v10 macro {b} cm", "OK" if b in (None, a) else "MISMATCH")
print(out, len(N), "macros")

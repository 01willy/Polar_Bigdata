"""v13 manuscript macros from the Fig. 4 / Fig. 5 source data (outputs/figures/paper/v14/source_data/*.json) -> paper/manuscript/shared_v14/numbers_v14.tex.
Only numbers printed in the v13 figures: Lena Delta observed-vs-predicted correlations (Fig. 5b), mean bias in the thinnest ALT class (Fig. 5c)."""
import json, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[2]
f5 = json.loads((ROOT / "outputs/figures/paper/v14/source_data/Fig5_products.json").read_text())
def cm(v):            # one decimal, true minus, explicit plus for positive biases
    return ("−" if v < 0 else "+") + f"{abs(v):.1f}"
out = ["% numbers_v14.tex: generated by scripts/2_evaluation/v14_numbers.py from the Fig. 5 source data (v13). Do not edit."]
b = f5["b"]["values"]
for key, name in (("Ro", "Physics + residual ML"), ("Wei", "Wei 2026"), ("Liu", "Liu 2024")):
    out.append(r"\newcommand{\nrLe%s}{%.2f}" % (key, b[name]["r"]))
    out.append(r"\newcommand{\nbiasLeAll%s}{%s}" % (key, cm(b[name]["bias_cm"])))
c = f5["c"]["values"]
for reg, rk in (("Lena", "Le"), ("Alaska", "Ak")):
    for key, name in (("Ro", "Physics + residual ML"), ("Wei", "Wei 2026"), ("Liu", "Liu 2024"), ("Ccifour", "ESA CCI v4"), ("Ccifive", "ESA CCI v5")):
        v = c[reg][name]["< 30"]
        if v is not None:
            out.append(r"\newcommand{\nbias%sThin%s}{%s}" % (rk, key, cm(v)))
    out.append(r"\newcommand{\nthinN%s}{%s}" % (rk, f"{c[reg]['cell_years_per_class']['< 30']:,}"))
out.append(r"\newcommand{\nccLeN}{%s}" % f"{f5['b']['n']:,}")
p = ROOT / "paper/manuscript/shared_v14/numbers_v14.tex"; p.write_text("\n".join(out) + "\n"); print(p); print("\n".join(out))

# ---- Fig. 7 (v13.1): linear trend of the yearly maps 2011-2024 (cm per decade), from the figure source data
f7p = ROOT / "outputs/figures/paper/v14/source_data/Fig7_maps.json"
if f7p.exists():
    f7 = json.loads(f7p.read_text())
    st = (f7.get("e") or f7.get("c") or {}).get("stats", {})          # v13.2: trend panel is e (three regions); v13.1: c (two regions)
    for reg, rk in (("Alaska", "Ak"), ("Lena Delta", "Le"), ("Canada (NW)", "Ca")):
        if reg in st:
            v = st[reg]
            out.append(r"\newcommand{\ntrend%s}{%s}" % (rk, cm(v["mean_cm_per_decade"])))
            out.append(r"\newcommand{\ntrendlo%s}{%s}" % (rk, cm(v["p05"])))
            out.append(r"\newcommand{\ntrendhi%s}{%s}" % (rk, cm(v["p95"])))
            out.append(r"\newcommand{\ntrendpos%s}{%d}" % (rk, round(100 * v["frac_positive"])))
    import numpy as _np
    ser = (f7.get("d") or {}).get("series", {})                        # v13.2: d = regional mean anomaly series, three regions
    for reg, rk in (("Alaska", "Ak"), ("Lena", "Le"), ("Canada", "Ca")):
        if reg in ser:
            pr, ob = ser[reg]["predicted"], ser[reg]["observed"]; yrs = sorted(set(pr) & set(ob))
            out.append(r"\providecommand{\nanobsn%s}{}\renewcommand{\nanobsn%s}{%d}" % (rk, rk, len(yrs)))
            if len(yrs) >= 2:
                pv = _np.array([pr[y] for y in yrs]); ov = _np.array([ob[y]["mean"] for y in yrs])
                out.append(r"\providecommand{\nanobsr%s}{}\renewcommand{\nanobsr%s}{%.2f}" % (rk, rk, _np.corrcoef(pv, ov)[0, 1]))
                out.append(r"\providecommand{\nanobssame%s}{}\renewcommand{\nanobssame%s}{%d}" % (rk, rk, int((_np.sign(pv) == _np.sign(ov)).sum())))
                out.append(r"\providecommand{\nanobsyrs%s}{}\renewcommand{\nanobsyrs%s}{%s–%s}" % (rk, rk, yrs[0], yrs[-1]))
                out.append(r"\providecommand{\nanobsrange%s}{}\renewcommand{\nanobsrange%s}{%.1f}" % (rk, rk, ov.max() - ov.min()))
                out.append(r"\providecommand{\nanpredrange%s}{}\renewcommand{\nanpredrange%s}{%.1f}" % (rk, rk, pv.max() - pv.min()))
    abc = (f7.get("a_b_c") or {}).get("regions", {})
    for reg, rk in (("Alaska", "Ak"), ("Lena Delta", "Le"), ("Canada (NW)", "Ca")):
        if reg in abc:
            out.append(r"\providecommand{\nncellmap%s}{}\renewcommand{\nncellmap%s}{%s}" % (rk, rk, f"{abc[reg]['n_cells_mapped']:,}"))
            out.append(r"\providecommand{\naoa%s}{}\renewcommand{\naoa%s}{%.0f}" % (rk, rk, 100 * abc[reg]["frac_inside_aoa"]))
    p = ROOT / "paper/manuscript/shared_v14/numbers_v14.tex"; p.write_text("\n".join(out) + "\n"); print("Fig. 7 macros added")

# ---- label units (v13.2, 2026-10-20): sites (observation locations, coordinates rounded to 0.0001 deg) versus 1 km cells (0.009 deg rule of the map grid)
import pandas as pd, numpy as np
lab = pd.read_csv(ROOT / "data/processed/v5/labels_cell_year_v5.csv", usecols=["loc_id", "region", "year", "in_forcing", "lat", "lon"]); lab = lab[lab.in_forcing == 1]
CELL = 0.009
ky = np.floor(lab.lat / CELL).astype(int); dx = CELL / np.cos(np.radians((ky + 0.5) * CELL)); kx = np.floor(lab.lon / dx).astype(int)
lab["cell"] = ky.astype(str) + "_" + kx.astype(str)
tot_cells = tot_cy = 0
for reg, rk in (("Alaska", "Ak"), ("Lena", "Le"), ("Canada", "Ca")):
    g = lab[lab.region == reg]; ncell = g.cell.nunique(); ncy = len(g.groupby(["cell", "year"]).size())
    out.append(r"\newcommand{\nnkmcell%s}{%s}" % (rk, f"{ncell:,}")); out.append(r"\newcommand{\nnkmcy%s}{%s}" % (rk, f"{ncy:,}"))
    mx = int(g.groupby(["cell", "year"]).size().max()); out.append(r"\newcommand{\nnkmmax%s}{%s}" % (rk, f"{mx:,}"))
    tot_cells += ncell; tot_cy += ncy
out.append(r"\newcommand{\nnkmcellAll}{%s}" % f"{tot_cells:,}"); out.append(r"\newcommand{\nnkmcyAll}{%s}" % f"{tot_cy:,}")
p = ROOT / "paper/manuscript/shared_v14/numbers_v14.tex"; p.write_text("\n".join(out) + "\n"); print("label-unit macros added")

# ---- Fig. 6 (v13.2, 2026-10-20): one common year for all regions, three rows; these macros override the v9 / v11 values of the same names
# (numbers_v13.tex is read last, so \providecommand + \renewcommand replaces an existing definition and defines a missing one).
f6p = ROOT / "outputs/figures/paper/v14/source_data/Fig6_product_maps.json"
if f6p.exists():
    f6 = json.loads(f6p.read_text()); RK6 = {"Alaska": "Ak", "Lena": "Le", "Canada": "Ca"}
    BAND = {"(59, 64]": "South", "(64, 66]": "Int", "(66, 68]": "Mid", "(68, 70]": "Foot", "(70, 72]": "North"}

    def setm(k, v):
        out.append(r"\providecommand{\n%s}{}\renewcommand{\n%s}{%s}" % (k, k, v))

    setm("feYear", str(f6["year_used"]))
    if "colour_range" in f6:                                   # v13 (one range for all maps)
        cr = f6["colour_range"]; setm("feLo", f"{cr['lo_cm']:.0f}"); setm("feHi", f"{cr['hi_cm']:.0f}")
    for reg, v in f6["values"].items():
        r = RK6[reg]; ts = v["product_training_sites"]
        setm(f"fe{r}N", str(v["n_common_cells"])); setm(f"fe{r}Year", str(v["year"]))
        setm(f"fe{r}Nobs", str(v["n_observed_cells"])); setm(f"fe{r}Nlab", f"{v['n_labels']:,}")
        setm(f"fe{r}NearWei", str(ts["n_common_within_25km"])); setm(f"fe{r}FarWei", str(ts["n_common_gt25km"]))
        for k, name in (("Oof", "physics_residual_ml_block_cv"), ("Wei", "wei_2026"), ("Liu", "liu_2024")):
            setm(f"fe{r}{k}", f"{v['rmse_common_cm'][name]:.1f}")
            cells_key = {"physics_residual_ml_block_cv": "physics_residual_ml_block_cv_cm", "wei_2026": "wei_2026_cm", "liu_2024": "liu_2024_cm"}[name]
            bias = (sum(c_[cells_key] - c_["observed_cm"] for c_ in v["cells"]) / len(v["cells"])) if v.get("cells") else v["bias_common_cm"][name]
            setm(f"fe{r}Bias{k}", cm(bias))                       # mean over the listed cells (avoids the double rounding of the 2-decimal summary)
            if "r_common" in v:                                 # v14: correlation at the common cells (printed in Fig. 6 d, h, l)
                setm(f"fe{r}R{k}", f"{v['r_common'][name]:.2f}")
        if "colour_range_cm" in v:                                # v14: per-region colour range
            setm(f"fe{r}Lo", f"{v['colour_range_cm'][0]:.0f}"); setm(f"fe{r}Hi", f"{v['colour_range_cm'][1]:.0f}")
        if reg == "Alaska":                          # map-level product − our map by latitude band × elevation class (text: Foot = 68–70°N, Mtn = > 600 m)
            for rec in v["band_differences"]["rows"]:
                tag = BAND[rec["band"]] + ("Mtn" if ">" in rec["mtn"] else "Low")
                for p in ("wei", "liu"):
                    if rec[f"{p}_minus_ours_cm"] is not None:
                        setm(f"mapAk{tag}{p.capitalize()}", cm(rec[f"{p}_minus_ours_cm"]))
    p = ROOT / "paper/manuscript/shared_v14/numbers_v14.tex"; p.write_text("\n".join(out) + "\n"); print("Fig. 6 macros added:", list(f6["values"]))

